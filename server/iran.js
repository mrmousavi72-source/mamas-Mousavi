// Allow up to this distance outside the coarse outline.
const TOLERANCE_KM = 25;
const BUFFERED = turf.buffer(IRAN_OUTLINE, TOLERANCE_KM, { units: 'kilometers' });

function isInsideIran([lng, lat]) {
  return turf.booleanPointInPolygon(turf.point([lng, lat]), BUFFERED);
}

module.exports = { isInsideIran };
